#!/usr/bin/env python3
"""Writes src/console/ui/width_table.zig, the console's character widths,
from the Unicode Character Database (the files pinned below by SHA-256).

    tools/gen-width-table.py [--ucd DIR]

Zero columns: general categories Mn, Me and Cf (marks and format
characters), the Hangul Jamo medial vowels and final consonants
(U+1160..U+11FF), which join the syllable before them, and the emoji skin
tone modifiers (Emoji_Modifier), which join the emoji before them; U+00AD SOFT HYPHEN
keeps one column, as wcwidth does. Two columns: East Asian Width W and F,
and Emoji_Presentation. Everything else is one column. --ucd reads the
files from DIR instead of downloading them.
"""
import argparse
import hashlib
import os
import re
import subprocess
import urllib.request

VERSION = "16.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
FILES = {
    "extracted/DerivedGeneralCategory.txt": "7676ab755a41ef82108460238569e60ad65c191ddafe61b36c6765ec1353f293",
    "EastAsianWidth.txt": "43adc76c0686a42cb370764eb8cfe2b2a45b10b855e5572a2db4a0eecce15d5b",
    "emoji/emoji-data.txt": "f1365a5173eee18e1f98b240cdc492e84a25f1ce7e0c9d1094eb29c41a22696a",
}
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "console", "ui", "width_table.zig")
LINE = re.compile(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([A-Za-z_]+)")


def load(name, ucd):
    if ucd:
        data = open(os.path.join(ucd, os.path.basename(name)), "rb").read()
    else:
        with urllib.request.urlopen(BASE + name) as r:
            data = r.read()
    got = hashlib.sha256(data).hexdigest()
    if got != FILES[name]:
        raise SystemExit(f"{name}: SHA-256 {got}, expected {FILES[name]}")
    return data.decode("utf-8")


def ranges(text, values):
    out = []
    for line in text.splitlines():
        m = LINE.match(line)
        if m and m.group(3) in values:
            lo = int(m.group(1), 16)
            out.append((lo, int(m.group(2), 16) if m.group(2) else lo))
    return out


def merge(rs):
    out = []
    for lo, hi in sorted(rs):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def subtract(rs, cps):
    out = []
    for lo, hi in rs:
        cur = lo
        for cp in sorted(c for c in cps if lo <= c <= hi):
            if cur < cp:
                out.append((cur, cp - 1))
            cur = cp + 1
        if cur <= hi:
            out.append((cur, hi))
    return out


def minus(rs, cut):
    """`rs` without any code point of `cut` (both sorted and merged)."""
    out = []
    for lo, hi in rs:
        cur = lo
        for clo, chi in cut:
            if chi < cur or clo > hi:
                continue
            if clo > cur:
                out.append((cur, clo - 1))
            cur = max(cur, chi + 1)
            if cur > hi:
                break
        if cur <= hi:
            out.append((cur, hi))
    return out


def zig(name, doc, rs):
    cells = [f".{{ .lo = 0x{lo:04X}, .hi = 0x{hi:04X} }}," for lo, hi in rs]
    lines = [f"/// {doc}", f"pub const {name} = [_]Range{{"]
    for i in range(0, len(cells), 2):
        lines.append("    " + " ".join(cells[i : i + 2]))
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucd")
    args = ap.parse_args()
    gc = load("extracted/DerivedGeneralCategory.txt", args.ucd)
    eaw = load("EastAsianWidth.txt", args.ucd)
    emoji = load("emoji/emoji-data.txt", args.ucd)

    zero = merge(subtract(ranges(gc, {"Mn", "Me", "Cf"}) + [(0x1160, 0x11FF)] + ranges(emoji, {"Emoji_Modifier"}), {0x00AD}))
    # Below U+0300 the console answers 1 without a lookup.
    zero = [(max(lo, 0x300), hi) for lo, hi in zero if hi >= 0x300]
    wide = merge(ranges(eaw, {"W", "F"}) + ranges(emoji, {"Emoji_Presentation"}))
    # A zero-width code point is never also wide.
    wide = minus(wide, zero)

    header = f"""//! Character width data: ranges of code points that take two columns
//! (East Asian Width W and F, and Emoji_Presentation) or none (general
//! categories Mn, Me and Cf, the Hangul medial vowels and final consonants,
//! and the emoji skin tone modifiers). Generated by tools/gen-width-table.py from Unicode {VERSION}
//! (DerivedGeneralCategory.txt, EastAsianWidth.txt, emoji-data.txt); do not
//! edit by hand. A wrong width only misaligns a row (the screen clips and
//! pads every row).
//! Unicode License v3: see THIRD_PARTY_NOTICES part C.

pub const Range = struct {{ lo: u21, hi: u21 }};
"""
    body = "\n\n".join([
        zig("wide", "Sorted, non-overlapping. Two columns.", wide),
        zig("zero", "Sorted, non-overlapping. Zero columns.", zero),
    ])
    with open(OUT, "w") as f:
        f.write(header + "\n" + body + "\n")
    # zig fmt aligns the columns.
    subprocess.run(["zig", "fmt", OUT], check=True, stdout=subprocess.DEVNULL)
    print(f"{OUT}: {len(wide)} wide ranges, {len(zero)} zero ranges")


if __name__ == "__main__":
    main()
