#!/usr/bin/env python3
"""Writes src/http/core/h2/huffman_table.zig, the HPACK Huffman tables, from
nghttp2's lib/nghttp2_hd_huffman_data.c (itself generated by nghttp2's
mkhufftbl.py from RFC 7541 Appendix B).

    tools/gen_huffman_table.py <nghttp2>/lib/nghttp2_hd_huffman_data.c

The pinned source is xuckless/nghttp2 0f8bc1c (v1.70.0 + the RFC 9113
patch). The symbol table keeps symbols 0..255 and drops EOS (256): the
encoder never emits it, and its pad is all ones. The decode table is
nghttp2's 257 x 16 nibble FSM unchanged, row 256 the sticky fail state.
The output is formatted with $ZIG fmt (default ~/.local/zig/0.17.0/zig).
"""
import os
import re
import subprocess
import sys

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "http", "core", "h2", "huffman_table.zig")
SYM = re.compile(r"\{\s*(\d+)\s*,\s*0x([0-9A-Fa-f]+)U\s*\}")
ENTRY = re.compile(r"\{\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*\}")


def section(src, start):
    i = src.index(start)
    j = src.index("\n};", i)
    return src[i + len(start):j]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = open(sys.argv[1]).read()

    syms = [(int(n), int(c, 16)) for n, c in SYM.findall(section(src, "huff_sym_table[] = {"))]
    assert len(syms) == 257, len(syms)
    for n, c in syms:
        assert 5 <= n <= 30, n
        assert c < 1 << 32 and c & ((1 << (32 - n)) - 1) == 0, (n, hex(c))
    assert syms[256] == (30, 0xFFFFFFFC), syms[256]

    entries = [tuple(int(x, 16) for x in e) for e in ENTRY.findall(section(src, "huff_decode_table[][16] = {"))]
    assert len(entries) == 257 * 16, len(entries)
    for f, fl, s in entries:
        assert f <= 0x100 and fl & ~0x03 == 0 and s <= 0xFF, (f, fl, s)
    rows = [entries[i * 16:(i + 1) * 16] for i in range(257)]
    assert all(e == (0x100, 0, 0) for e in rows[256]), rows[256]

    out = [
        "// Translated from nghttp2 (MIT, Copyright (c) 2012, 2014, 2015, 2016",
        "// Tatsuhiro Tsujikawa; Copyright (c) 2012, 2014, 2015, 2016 nghttp2",
        "// contributors), v1.70.0 via Anole's fork xuckless/nghttp2 0f8bc1c,",
        "// lib/nghttp2_hd_huffman_data.c. See LICENSE.nghttp2 and THIRD_PARTY_NOTICES.",
        "//",
        "// Generated by tools/gen_huffman_table.py from lib/nghttp2_hd_huffman_data.c",
        "// (itself generated by nghttp2's mkhufftbl.py from RFC 7541 Appendix B);",
        "// do not edit by hand.",
        "",
        "//! The HPACK Huffman code (RFC 7541 Appendix B) and nghttp2's 4-bit decode",
        "//! FSM. Unlike nghttp2's huff_sym_table, `sym_table` has no EOS entry: the",
        "//! encoder never emits EOS, its padding is all ones, and a `u8` index needs",
        "//! no bound check.",
        "",
        "/// A code, MSB-aligned in 32 bits (nghttp2's header says LSB; it is not).",
        "pub const Sym = struct { nbits: u8, code: u32 };",
        "",
        "/// One FSM transition: the next state, `accepted`/`emits` flags and the",
        "/// symbol emitted when `emits` is set. 4 bytes, as nghttp2's.",
        "pub const Entry = extern struct { fstate: u16, flags: u8, sym: u8 };",
        "",
        "/// The state is a valid end: the bits so far are whole symbols plus at",
        "/// most 7 bits of EOS prefix (NGHTTP2_HUFF_ACCEPTED).",
        "pub const accepted: u8 = 0x01;",
        "/// The transition emits `sym` (NGHTTP2_HUFF_SYM).",
        "pub const emits: u8 = 0x02;",
        "/// The sticky failure state: EOS was decoded or padding ran over 7 bits.",
        "pub const fail_state: u16 = 0x100;",
        "",
        "pub const sym_table = [256]Sym{",
    ]
    for i, (n, c) in enumerate(syms[:256]):
        out.append(f"    .{{ .nbits = {n}, .code = 0x{c:08X} }}, // {i}")
    out.append("};")
    out.append("")
    out.append("/// Indexed by state, then by the next nibble.")
    out.append("pub const decode_table = [257][16]Entry{")
    for i, row in enumerate(rows):
        out.append(f"    // {i}")
        out.append("    .{")
        for f, fl, s in row:
            out.append(f"        .{{ .fstate = 0x{f:03X}, .flags = 0x{fl:02X}, .sym = 0x{s:02X} }},")
        out.append("    },")
    out.append("};")

    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    zig = os.environ.get("ZIG", os.path.expanduser("~/.local/zig/0.17.0/zig"))
    subprocess.run([zig, "fmt", OUT], check=True, stdout=subprocess.DEVNULL)
    print(f"{OUT}: {len(syms) - 1} symbols, {len(rows)} states")


if __name__ == "__main__":
    main()
