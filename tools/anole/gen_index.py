#!/usr/bin/env python3
"""Regenerates templates/index.zig from the templates/<name>/ directories.

    python3 tools/anole/gen_index.py

Run it after adding, removing or renaming a template file; the cli-test
fails on a file the index does not list. Template names, summaries and the
text printed after `anole new` are in META below.
"""
import os
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
os.chdir(root)

META = {
    "minimal": ("A small JSON API: typed routes, validation, health, OpenAPI docs.",
                "  zig build run            # http://localhost:3000, API docs at /docs\n  zig build test           # in-memory tests\n"),
    "rest-postgres": ("A todo API on PostgreSQL: typed CRUD, rules, conflicts as 409.",
                      "  docker compose up -d     # Postgres for development (db/schema.sql is applied on first start)\n  zig build run            # http://localhost:3000, API docs at /docs\n"),
    "realtime": ("A WebSocket chat with rooms and a browser page.",
                 "  zig build run            # http://localhost:3000: open it in two tabs\n  zig build test\n"),
    "grpc": ("A gRPC service that also speaks gRPC-Web, Connect and REST.",
             "  zig build run            # http://localhost:3000, docs at /docs\n  zig build test\n"),
    "full": ("Every feature that runs without an external service, as one app.",
             "  zig build run            # http://localhost:3000, docs at /docs\n  zig build test\n"),
}
ORDER = ["minimal", "rest-postgres", "realtime", "grpc", "full"]

HEAD = '''//! The project templates of `anole new` and `anole init`, embedded in the CLI.
//! Each template is a directory under templates/ with its files. This file is
//! generated by `python3 tools/anole/gen_index.py` (rerun it when a file is
//! added or renamed); a test in tools/anole/main.zig fails on a file it does
//! not list.

pub const File = struct {
    /// Relative to the project root, '/'-separated.
    path: []const u8,
    /// The file's text; `{{name}}` is replaced by the project name.
    data: []const u8,
};

pub const Template = struct {
    name: []const u8,
    summary: []const u8,
    /// Printed after the project is created (lines, already indented).
    next_steps: []const u8,
    files: []const File,
};

'''


def lit(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


for name in os.listdir("templates"):
    if os.path.isdir(os.path.join("templates", name)) and name not in META:
        sys.exit("templates/%s is not in META" % name)

out = [HEAD, "pub const templates = [_]Template{\n"]
for t in ORDER:
    d = os.path.join("templates", t)
    files = []
    for dirpath, dirs, fs in os.walk(d):
        dirs.sort()
        for f in fs:
            files.append(os.path.relpath(os.path.join(dirpath, f), d).replace(os.sep, "/"))
    files.sort(key=lambda p: (p != "build.zig", p))
    out.append("    .{\n        .name = %s,\n        .summary = %s,\n        .next_steps = %s,\n        .files = &.{\n" % (lit(t), lit(META[t][0]), lit(META[t][1])))
    for p in files:
        out.append("            .{ .path = %s, .data = @embedFile(%s) },\n" % (lit(p), lit(t + "/" + p)))
    out.append("        },\n    },\n")
out.append("};\n")
open("templates/index.zig", "w").write("".join(out))
